# ORBE & ONIX | Safe face reference setup for Blender 4.5.15
# IMPORTANT: Run this .py file only. Open the .blend project with File > Open.
# Photos are auto-searched in Downloads/faces, beside the .blend file,
# and in a references subfolder beside the .blend file.

import bpy
import os
import math

PHOTO_FILES = {
    "FRONT": "20261110_221139.jpg",
    "THREE_QUARTER": "20261110_221314.jpg",
    "PROFILE": "20261110_221347.jpg",
}

if not bpy.data.filepath:
    raise RuntimeError("Save your project as a .blend file first (File > Save As), then run this .py script.")

project_dir = os.path.dirname(bpy.data.filepath)

# Exact folder visible in the user's Blender system log, plus useful fallbacks.
search_dirs = [
    r"D:\Users\BiggyHouse\Downloads\faces",
    os.path.join(os.path.dirname(project_dir), "faces"),
    os.path.join(project_dir, "faces"),
    os.path.join(project_dir, "references"),
    project_dir,
]

def locate_photo(filename):
    for folder in search_dirs:
        candidate = os.path.join(folder, filename)
        if os.path.isfile(candidate):
            return os.path.abspath(candidate)
    return None

photo_paths = {key: locate_photo(filename) for key, filename in PHOTO_FILES.items()}
missing = [PHOTO_FILES[key] for key, path in photo_paths.items() if path is None]
if missing:
    checked = "\n".join(search_dirs)
    raise RuntimeError(
        "Photos not found: " + ", ".join(missing) +
        "\nFolders checked:\n" + checked +
        "\nKeep the JPG files in D:\\Users\\BiggyHouse\\Downloads\\faces or in a references folder beside the .blend."
    )

# Create/reuse the references collection. Never clear or delete other scene objects.
collection_name = "03_PHOTO_REFERENCES"
refs_collection = bpy.data.collections.get(collection_name)
if refs_collection is None:
    refs_collection = bpy.data.collections.new(collection_name)
    bpy.context.scene.collection.children.link(refs_collection)

refs_collection.hide_viewport = False
refs_collection.hide_render = False

# Ensure the collection is enabled in the active view layer.
def unhide_layer_collection(layer_collection, target):
    if layer_collection.collection == target:
        layer_collection.exclude = False
        layer_collection.hide_viewport = False
        return True
    for child in layer_collection.children:
        if unhide_layer_collection(child, target):
            return True
    return False

unhide_layer_collection(bpy.context.view_layer.layer_collection, refs_collection)

# Rerunnable: remove only references generated by this script.
for obj in list(refs_collection.objects):
    if obj.name.startswith("OO_REF_"):
        bpy.data.objects.remove(obj, do_unlink=True)

def add_ref(label, path, location, rotation, size):
    image = bpy.data.images.load(path, check_existing=True)
    image.pack()
    empty = bpy.data.objects.new("OO_REF_" + label, None)
    empty.empty_display_type = 'IMAGE'
    empty.data = image
    empty.empty_display_size = size
    empty.empty_image_depth = 'BACK'
    empty.empty_image_side = 'DOUBLE_SIDED'
    empty.color[3] = 0.78
    empty.location = location
    empty.rotation_euler = rotation
    refs_collection.objects.link(empty)
    empty.hide_set(False)
    empty.hide_select = False
    return empty

# Blender front view looks toward -Y. The photo is placed behind the head.
front = add_ref("FRONT", photo_paths["FRONT"],
                (0.0, 0.78, 0.0), (math.radians(90), 0, 0), 2.0)

# Right orthographic view looks from +X. Profile reference is on the +X side.
profile = add_ref("PROFILE", photo_paths["PROFILE"],
                  (0.78, 0.0, 0.0), (math.radians(90), 0, math.radians(90)), 2.0)

# Three-quarter reference is parked to the left and can be toggled in the Outliner.
threeq = add_ref("THREE_QUARTER", photo_paths["THREE_QUARTER"],
                 (-1.15, 0.0, 0.0), (math.radians(90), 0, math.radians(-90)), 2.0)

# Safe viewport settings for the older FirePro GPU: Solid only, no EEVEE preview.
for screen in bpy.data.screens:
    for area in screen.areas:
        if area.type == 'VIEW_3D':
            space = area.spaces.active
            space.region_3d.view_perspective = 'ORTHO'
            space.region_3d.view_rotation = (math.sqrt(0.5), math.sqrt(0.5), 0, 0)
            space.region_3d.view_location = (0, 0, 0)
            space.region_3d.view_distance = 3.2
            space.overlay.show_floor = True
            space.shading.type = 'SOLID'
            try:
                space.shading.light = 'STUDIO'
                space.shading.show_xray = True
                space.shading.xray_alpha = 0.35
            except Exception:
                pass

# Workbench avoids relying on EEVEE for still renders in this reference stage.
try:
    bpy.context.scene.render.engine = 'BLENDER_WORKBENCH'
except Exception:
    pass

bpy.ops.object.select_all(action='DESELECT')
front.select_set(True)
bpy.context.view_layer.objects.active = front

print("ORBE & ONIX: references loaded successfully.")
for key, path in photo_paths.items():
    print(key + ": " + path)
print("Viewport set to Solid with X-Ray. Front: Numpad 1 | Profile: Numpad 3.")
print("Do not use Rendered or Material Preview on this FirePro setup.")
